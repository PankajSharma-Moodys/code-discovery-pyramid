#!/usr/bin/env python3
"""Regenerate the README command table from each command's `SPEC`.

    python3 scripts/gen_readme.py           # rewrite README.md
    python3 scripts/gen_readme.py --check   # exit 1 if README.md is stale
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from cdp.commands import specs  # noqa: E402

BEGIN = "<!-- BEGIN COMMANDS: generated by scripts/gen_readme.py from each command's SPEC -->"
END = "<!-- END COMMANDS -->"


def render() -> str:
    out = [BEGIN, ""]
    for title, group in specs():
        out += ["### " + title, "", "| Command | What it does | Next / useful flags |", "|---|---|---|"]
        out += ["| `%s` | %s | %s |" % (s.usage, s.what, s.next) for s in group]
        out.append("")
    out.append(END)
    return "\n".join(out)


def apply(text: str) -> str:
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + render() + text[b:]


def main(argv) -> int:
    path = ROOT / "README.md"
    old = path.read_text()
    new = apply(old)
    if "--check" in argv:
        if new != old:
            print("README.md command table is stale: run python3 scripts/gen_readme.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
