"""The `code` artifact: source text of `source`-role files, for code search (ANNOTATIONS_PLAN P12).

`{"head": <commit>, "files": {path: text}}`, lines joined with `\\n` exactly as `read_lines`
split them, so a line number here is the line number every define row and anchor uses. Text is
read from the tree the scan read (the commit when the tree is clean; the working file when it is
dirty -- queries say so). No index: search is a plain scan. Rebuilt in full by `scan` and
`refresh` (it is a pure function of the inventory and the tree, so it cannot drift from them).
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

from .util import MAX_PARSE_BYTES, read_lines

# Files that announce themselves as machine-written: their text is noise for a search.
GENERATED_MARKERS = ("@generated", "code generated", "do not edit", "auto-generated", "autogenerated")
# Languages whose string literals and comments the counter below understands.
_LITERAL_EXTS = (".java", ".cs", ".scala", ".kt", ".go", ".ts", ".js")


def _generated(lines: List[str]) -> bool:
    head = " ".join(lines[:3]).lower()
    return any(m in head for m in GENERATED_MARKERS)


def build_code(repo: Path, inventory: Dict) -> Dict:
    files: Dict[str, str] = {}
    for entry in inventory["files"]:
        if entry["role"] != "source" or entry["binary"] or entry["bytes"] > MAX_PARSE_BYTES:
            continue
        lines = read_lines(Path(repo) / entry["path"])
        if not lines or _generated(lines):
            continue
        files[entry["path"]] = "\n".join(lines)
    return {"head": inventory["head"], "files": dict(sorted(files.items()))}


def member_index(symbols: Dict) -> Dict[str, List[Tuple[int, int, str, str]]]:
    """`file -> [(line, end_line or 0, fqn, kind)]` sorted by line, from xref definition sites."""
    out: Dict[str, List[Tuple[int, int, str, str]]] = {}
    for fqn, entry in symbols.items():
        for site in entry.get("sites", []) or []:
            out.setdefault(site["file"], []).append(
                (site["anchor"]["line"], site.get("end_line") or 0, fqn, entry.get("kind", "")))
    for rows in out.values():
        rows.sort()
    return out


_TYPE_KINDS = ("field", "constant")


def owner_of(rows: List[Tuple[int, int, str, str]], line: int) -> Optional[str]:
    """The member whose declared extent holds `line` (innermost = latest start); else a define
    on that very line; else the nearest preceding define that has no extent and is not a field
    or constant (a type, or a member of a language whose rows carry no end line); else None."""
    best = None
    for start, end, fqn, _kind in rows:
        if start > line:
            break
        if end and line <= end:
            best = fqn
    if best:
        return best
    for start, _end, fqn, _kind in rows:
        if start == line:
            return fqn
    for start, end, fqn, kind in reversed(rows):
        if start < line and not end and kind not in _TYPE_KINDS:
            return fqn
    return None


def scan_lines(text: str, needle: str) -> Iterable[Tuple[int, str]]:
    """`(line number, line)` for each line containing `needle` (already lower-cased), case-insensitive."""
    pos = 0
    low = text.lower()
    while True:
        hit = low.find(needle, pos)
        if hit < 0:
            return
        start = text.rfind("\n", 0, hit) + 1
        end = text.find("\n", hit)
        end = len(text) if end < 0 else end
        yield text.count("\n", 0, start) + 1, text[start:end]
        pos = end + 1


def count_literals(path: str, text: str, first: int, last: int) -> int:
    """String literals (`"..."` and `\"\"\"` blocks) in lines `first..last`, comments and char
    literals skipped. A member's body only: 0 for languages it does not understand."""
    if not path.endswith(_LITERAL_EXTS):
        return 0
    body = "\n".join(text.split("\n")[first - 1:last])
    n, i, size = 0, 0, len(body)
    while i < size:
        c = body[i]
        pair = body[i:i + 2]
        if pair == "//":
            nl = body.find("\n", i)
            i = size if nl < 0 else nl
        elif pair == "/*":
            end = body.find("*/", i + 2)
            i = size if end < 0 else end + 2
        elif body.startswith('"""', i):
            end = body.find('"""', i + 3)
            n += 1
            i = size if end < 0 else end + 3
        elif c == '"':
            n += 1
            i += 1
            while i < size and body[i] not in '"\n':
                i += 2 if body[i] == "\\" else 1
            i += 1
        elif c == "'":
            i += 1
            while i < size and body[i] not in "'\n":
                i += 2 if body[i] == "\\" else 1
            i += 1
        else:
            i += 1
    return n
