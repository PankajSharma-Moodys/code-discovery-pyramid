"""Opt-in install extras that edit files the user owns: a CLAUDE.md rule block and the
`mcp__cdp__*` permission. Both are idempotent, touch nothing outside what they add, and
`remove_*` undoes exactly that.

The CLAUDE.md text is generated from `guide_kinds` (the same table SKILL.md and the MCP tool
description use), so the kinds and the question -> kind rows cannot drift from the tool.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, List

from .guide_kinds import FLOW, KINDS
from .util import CdpError

BEGIN = "<!-- cdp:begin -- generated by `cdp install --claude-md`; edit outside these markers; `--remove-harness` removes this block -->"
END = "<!-- cdp:end -->"
_BLOCK = re.compile(r"\n?" + re.escape(BEGIN.split(" -- ")[0]) + r".*?" + re.escape(END) + r"\n?", re.S)

#: The six rows of the question -> kind table, in order. A kind missing from `KINDS` is skipped,
#: and one absent from `FLOW` takes its `summary`, so `jobs` appears as soon as the query side has it.
ROW_KINDS = ("symbol", "trace", "routes", "table", "config", "jobs")

PERMISSION = "mcp__cdp__*"
#: Marker recording that install (not the user) added PERMISSION, so removal takes only that.
ALLOW_STATE = ".cdp-allow-mcp"


def claude_md_block() -> str:
    flow = {kind: question for question, kind in FLOW}
    rows = []
    for kind in ROW_KINDS if "jobs" in KINDS else ROW_KINDS[:-1] + ("search",):
        if kind in KINDS:
            rows.append("| %s | `%s` |" % (flow.get(kind) or KINDS[kind]["summary"], kind))
    return "\n".join([
        BEGIN,
        "## CDP index (MUST use first)",
        "This repo is indexed by CDP: the MCP tool `cdp_query` (CLI `cdp query`). The index is available when the "
        "session-start status says it is ready, or when `cdp_query` kind `stats` answers. While it is available:",
        "",
        "1. **MUST use CDP for code discovery.** Locating a class, method, caller, route, table, config key or job "
        "starts with `cdp_query`, every time, not only for the first lookup of a task.",
        "2. **Do not grep first.** No grep/find/rg in Bash and no Grep/Glob tool for code until `cdp_query` has been "
        "tried for that lookup. Grep only when the answer is text the index does not hold (comments, non-code files) "
        "or when `cdp_query` found nothing and kind `coverage` shows the place was not examined.",
        "3. **Respect the cited ranges.** CDP answers cite `file:line` and `file:start-end`. Read code with exactly "
        "those ranges (Read `offset`/`limit`); never read a whole source file when a range is cited.",
        "4. **Confused? Ask CDP.** When unsure which kind, term or flag fits, call `cdp_help` (CLI `cdp help`) "
        "before falling back to anything else.",
        "5. **Remember these rules.** Keep a memory note (type feedback) that this repo is CDP-indexed and rules 1-4 "
        "apply, so they hold across sessions; when you notice you broke one, say so and update that note.",
        "",
        "| Question | `kind` |",
        "|---|---|",
    ] + rows + [END])


def install_claude_md(target: Path) -> List[str]:
    """Write or refresh the marked block in `<target>/CLAUDE.md`; create the file if absent."""
    path = target / "CLAUDE.md"
    block = claude_md_block()
    if not path.exists():
        path.write_text(block + "\n", encoding="utf-8")
        return ["wrote     %s (CDP block only)" % path]
    text = path.read_text(encoding="utf-8")
    if BEGIN.split(" -- ")[0] in text:
        if not _BLOCK.search(text):
            raise CdpError("%s has a CDP begin marker without its end marker; fix it, then re-run." % path)
        new = _BLOCK.sub(lambda m: ("\n" if m.group(0).startswith("\n") else "") + block + "\n", text, count=1)
        if new == text:
            return ["kept      %s (CDP block already current)" % path]
        path.write_text(new, encoding="utf-8")
        return ["updated   CDP block in %s" % path]
    sep = ("" if text.endswith("\n") else "\n") + "\n" if text else ""
    path.write_text(text + sep + block + "\n", encoding="utf-8")
    return ["appended  CDP block to %s" % path]


def remove_claude_md(target: Path) -> List[str]:
    path = target / "CLAUDE.md"
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    if not _BLOCK.search(text):
        return []
    new = _BLOCK.sub("", text, count=1)
    if not new.strip():
        new = ""
    if not new:
        path.unlink()
        return ["deleted   %s (only the CDP block was in it)" % path]
    path.write_text(new, encoding="utf-8")
    return ["removed   CDP block from %s" % path]


# ------------------------------------------------------------------ permissions


def _read_settings(path: Path) -> Dict:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        raise CdpError("%s is not valid JSON; refusing to overwrite it. Fix or move it, then re-run." % path)
    if not isinstance(data, dict):
        raise CdpError("%s does not contain a JSON object" % path)
    return data


def _write(path: Path, obj: Dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def install_allow_mcp(target: Path) -> List[str]:
    """Add `mcp__cdp__*` to `permissions.allow` in `<target>/.claude/settings.json`."""
    path = target / ".claude" / "settings.json"
    settings = _read_settings(path)
    perms = settings.get("permissions")
    if perms is not None and not isinstance(perms, dict):
        raise CdpError("%s: `permissions` must be an object; refusing to change it." % path)
    perms = settings.setdefault("permissions", {})
    allow = perms.get("allow")
    if allow is not None and not isinstance(allow, list):
        raise CdpError("%s: `permissions.allow` must be a list; refusing to change it." % path)
    allow = perms.setdefault("allow", [])
    state = path.parent / ALLOW_STATE
    notes = []
    if PERMISSION in allow:
        notes.append("kept      %s already in permissions.allow of %s" % (PERMISSION, path))
    else:
        allow.append(PERMISSION)
        _write(path, settings)
        state.write_text("added by `cdp install --allow-mcp`; `--remove-harness` removes `%s` from permissions.allow\n" % PERMISSION,
                         encoding="utf-8")
        notes.append("allow     added %s to permissions.allow in %s" % (PERMISSION, path))
    notes.append("          grants: every tool of the `cdp` MCP server without a prompt -- cdp_query, cdp_status, cdp_help "
                 "(read the index), cdp_scan, cdp_refresh, cdp_link (write only the index store under CDP_HOME; no "
                 "repository edits, no model calls). Nothing else.")
    return notes


def remove_allow_mcp(target: Path) -> List[str]:
    """Remove `mcp__cdp__*` only when install added it (the marker file says so)."""
    path = target / ".claude" / "settings.json"
    state = path.parent / ALLOW_STATE
    if not state.exists() or not path.exists():
        return []
    settings = _read_settings(path)
    perms = settings.get("permissions")
    allow = perms.get("allow") if isinstance(perms, dict) else None
    notes = []
    if isinstance(allow, list) and PERMISSION in allow:
        allow.remove(PERMISSION)
        if not allow:
            del perms["allow"]
        if not perms:
            del settings["permissions"]
        if settings:
            _write(path, settings)
        else:
            path.unlink()
        notes.append("removed   %s from permissions.allow in %s" % (PERMISSION, path))
    state.unlink()
    return notes
